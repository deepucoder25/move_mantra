<script>
document.addEventListener('DOMContentLoaded', function() {
  const scrollContainer = document.getElementById('reviewsScrollContainer');
  const btnLeft = document.getElementById('reviewBtnLeft');
  const btnRight = document.getElementById('reviewBtnRight');

  if (scrollContainer && btnLeft && btnRight) {
    btnLeft.addEventListener('click', function() {
      scrollContainer.scrollBy({ left: -360, behavior: 'smooth' });
    });
    btnRight.addEventListener('click', function() {
      scrollContainer.scrollBy({ left: 360, behavior: 'smooth' });
    });
  }
});
</script>
